# Creating a list
fruits = ["Apple", "Banana", "Mango", "Orange"]

# Display the list
print("Fruit List:", fruits)

# Accessing elements
print("First Fruit:", fruits[0])

# Adding an element
fruits.append("Grapes")
print("After Adding:", fruits)

# Removing an element
fruits.remove("Banana")
print("After Removing:", fruits)

# Loop through the list
print("All Fruits:")
for fruit in fruits:
    print(fruit)